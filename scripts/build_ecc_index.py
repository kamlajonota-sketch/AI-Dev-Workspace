#!/usr/bin/env python3
"""Generate a searchable inventory of the mirrored ECC source tree."""
from pathlib import Path
from collections import Counter

ROOT = Path(__file__).resolve().parents[1]
ECC = ROOT / "vendor" / "ecc"
OUTPUT = ROOT / "ECC_FILE_INDEX.md"

def main() -> int:
    if not ECC.is_dir():
        print("ECC mirror not found at vendor/ecc; run the sync-ecc workflow first.")
        return 1

    files = sorted(p.relative_to(ECC).as_posix() for p in ECC.rglob("*") if p.is_file() and ".git" not in p.parts)
    counts = Counter(path.split("/", 1)[0] if "/" in path else "(root)" for path in files)

    lines = [
        "# ECC Source File Index",
        "",
        "Generated by scripts/build_ecc_index.py. Source snapshot: vendor/ecc/.",
        "",
        f"- Total files: **{len(files)}**",
        "- Official upstream: https://github.com/affaan-m/ECC",
        "- This is a navigation index; read the relevant source file before applying a component.",
        "",
        "## Top-level file counts",
        "",
        "| Directory or root files | File count |",
        "|---|---:|",
    ]
    for name, count in sorted(counts.items(), key=lambda item: item[0].casefold()):
        lines.append(f"| {name} | {count} |")

    lines += ["", "## Key component locations", ""]
    key_paths = [
        "agents/", "skills/", "commands/", "rules/", "hooks/", "scripts/",
        "tests/", "workflows/", "integrations/", "mcp-configs/", "manifests/",
        "schemas/", "docs/", ".agents/", ".claude/", ".codex/", ".cursor/",
        ".opencode/", ".gemini/", ".kiro/", "plugins/", "src/",
    ]
    for path in key_paths:
        if any(p == path.rstrip("/") or p.startswith(path) for p in files):
            lines.append(f"- [vendor/ecc/{path}](vendor/ecc/{path})")

    lines += ["", "## Complete file list", ""]
    lines += [f"- vendor/ecc/{path}" for path in files]
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Indexed {len(files)} ECC files into {OUTPUT.name}")
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
